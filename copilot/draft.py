def _fill(text: str, facts: dict) -> str:
    for k, v in facts.items():
        text = text.replace("{{" + k + "}}", str(v))
    return text


def draft_reply(ticket_text, card, cls, kb, feedback=None):
    kb_ids = list(dict.fromkeys(card.kb_ids + ["KB-16"]))
    kb_block = "\n".join(f"[{k}] {kb[k]['topic']}: {kb[k]['guidance']}" for k in kb_ids if k in kb)
    placeholders = {k: v for k, v in card.allowed_facts.items() if v is not None}
    prompt = (
        f"DECISION CARD: category={card.category}, sub_intent={card.sub_intent}, action={card.action}, "
        f"team={card.team}, rule={card.rule_id}\n"
        f"WHAT THE REPLY MUST SAY: {RULE_GUIDE.get(card.rule_id, card.reason_plain)}\n"
        f"ALLOWED PLACEHOLDERS (key -> current value, write the key not the value): "
        f"{json.dumps({'{{' + k + '}}': str(v) for k, v in placeholders.items()}, ensure_ascii=False)}\n"
        f"CITED KB:\n{kb_block}\n"
        f"MERCHANT LANGUAGE: {cls['language']} | SENTIMENT: {cls['sentiment']}\n\n"
        f"TICKET:\n{ticket_text}"
    )
    if feedback:
        prompt += f"\n\nFEEDBACK ON PREVIOUS DRAFT: {feedback}"
    out = call_json(MODEL_DRAFT, SYSTEM, prompt, max_tokens=1000)
    raw = str(out.get("reply", "")).strip()
    return _fill(raw, placeholders), [kb[k]["guidance"] for k in kb_ids if k in kb]


def draft_and_guard(ticket, ext, cls, merchant, card, kb, store):
    text = ticket["merchant_message"]
    hits = store.query(text, k=3, namespace="kb") if store else []
    retrieval_score = max((s for _, s in hits), default=None)
    retrieved = [h for h, _ in hits]
    critic_issues, critic_pass = [], True

    if card.rule_id == "T":
        reply = ACK.get(cls["language"], ACK["English"]).format(team=card.team)
        kb_texts = [kb["KB-15"]["guidance"]]
        spec = True
    else:
        reply, kb_texts = draft_reply(text, card, cls, kb)
        spec = specificity(reply, card, ext.get("payment_id"))
        if not spec:
            reply, kb_texts = draft_reply(text, card, cls, kb, feedback=(
                "The draft was generic. Include at least one merchant-specific placeholder such as {{merchant_id}}"
                + (" or {{payment_id}}" if ext.get("payment_id") else "")
                + (" and end with a direct question" if card.action == "Ask for info" else "") + "."))
            spec = specificity(reply, card, ext.get("payment_id"))

    fw_status, fw_issues = firewall(reply, card, kb_texts)
    if card.rule_id != "T" and fw_status == "PASS":
        c = critic(text, card, cls["language"], reply, guidance=RULE_GUIDE.get(card.rule_id, ""), kb_texts=kb_texts)
        critic_pass, critic_issues = c["pass"], c["issues"]

    mode = send_mode(card, cls["confidence"], cls["sentiment"], card.block_auto and "repeat_contact" in card.flags,
                     fw_status, spec, critic_pass)
    return {
        "drafted_reply": reply, "send_mode": mode, "firewall_status": fw_status,
        "firewall_issue": "; ".join(fw_issues), "specificity_pass": spec,
        "critic_issues": "; ".join(critic_issues), "retrieval_score": retrieval_score,
        "kb_retrieved": ", ".join(retrieved),
        "kb_cited": ", ".join(dict.fromkeys(card.kb_ids + [k for k in retrieved if k in card.kb_ids])),
    }
